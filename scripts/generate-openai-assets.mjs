import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
/** Repository root (this file is `scripts/generate-openai-assets.mjs`). */
const ROOT = path.resolve(__dirname, "..");
const CONFIGS_DIR = path.join(ROOT, "configs");
const PROMPTS_DIR = path.join(ROOT, "prompts");
const OUT_DIR = path.resolve(process.cwd(), "src", "generated");
const OUT_FILE = path.join(OUT_DIR, "openai-assets.ts");

const COMMON_PROMPTS = [
  "output_verbosity_enforcement.v1.2.0.yaml",
  "cv_optimization_level_guidance.v1.1.0.yaml",
  "seniority_alignment.v2.0.0.yaml",
  "llm_responsibilities.yaml",
  "json_output_format.v1.1.0.yaml",
];

const PREPROCESSING_PROMPTS = [
  "cv_extractor.v1.2.3.yaml",
  "job_description_extractor.v1.1.1.yaml",
];

function toTemplateLiteralString(content) {
  return content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

async function readJson(relativePath) {
  const fullPath = path.join(ROOT, relativePath);
  return fs.readFile(fullPath, "utf-8");
}

async function collectPromptPaths() {
  const agentsRaw = await readJson(path.join("configs", "agents.json"));
  const agents = JSON.parse(agentsRaw);
  const promptPaths = new Set();

  for (const stage of agents.stages ?? []) {
    for (const agent of stage.agents ?? []) {
      if (agent.promptBase && agent.version) {
        promptPaths.add(`${agent.promptBase}.v${agent.version}.yaml`);
      }
    }
  }
  for (const file of COMMON_PROMPTS) {
    promptPaths.add(`common/${file}`);
  }
  for (const file of PREPROCESSING_PROMPTS) {
    promptPaths.add(`preprocessing/${file}`);
  }
  return [...promptPaths].sort();
}

async function generate() {
  const configs = {
    agents: await fs.readFile(path.join(CONFIGS_DIR, "agents.json"), "utf-8"),
    openai: await fs.readFile(path.join(CONFIGS_DIR, "openai.json"), "utf-8"),
  };
  const promptPaths = await collectPromptPaths();
  const prompts = {};

  for (const relative of promptPaths) {
    const full = path.join(PROMPTS_DIR, relative);
    prompts[relative] = await fs.readFile(full, "utf-8");
  }

  await fs.mkdir(OUT_DIR, { recursive: true });

  const lines = [];
  lines.push("/* Auto-generated by scripts/generate-openai-assets.mjs */");
  lines.push("export const embeddedConfigs: Record<string, string> = {");
  lines.push(`  "agents": \`${toTemplateLiteralString(configs.agents)}\`,`);
  lines.push(`  "openai": \`${toTemplateLiteralString(configs.openai)}\`,`);
  lines.push("};");
  lines.push("");
  lines.push("export const embeddedPrompts: Record<string, string> = {");
  for (const [rel, content] of Object.entries(prompts)) {
    lines.push(`  "${rel}": \`${toTemplateLiteralString(content)}\`,`);
  }
  lines.push("};");
  lines.push("");
  lines.push("export function getEmbeddedConfigJson(name: \"agents\" | \"openai\"): string | null {");
  lines.push("  return embeddedConfigs[name] ?? null;");
  lines.push("}");
  lines.push("");
  lines.push("export function getEmbeddedPromptText(relativePath: string): string | null {");
  lines.push("  return embeddedPrompts[relativePath] ?? null;");
  lines.push("}");

  await fs.writeFile(OUT_FILE, `${lines.join("\n")}\n`, "utf-8");
  console.log(`Generated ${OUT_FILE} with ${promptPaths.length} prompt files.`);
}

generate().catch((error) => {
  console.error(error);
  process.exit(1);
});
