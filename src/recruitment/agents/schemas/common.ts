export const InterviewQuestionSchema = z.object({
  id: z.string(),
  text: z.string(),
  difficulty: z.enum(['easy', 'medium', 'hard']),
  focus_area: z.string(),
});

/** Count easy / medium / hard (only these enum values should appear). */
export function countInterviewQuestionDifficulties(questions: { difficulty: string }[]): {
  easy: number;
  medium: number;
  hard: number;
  total: number;
} {
  let easy = 0;
  let medium = 0;
  let hard = 0;
  for (const q of questions) {
    if (q.difficulty === 'easy') easy += 1;
    else if (q.difficulty === 'medium') medium += 1;
    else if (q.difficulty === 'hard') hard += 1;
  }
  return { easy, medium, hard, total: questions.length };
}

/**
 * True when n >= 10 and each difficulty count is in [floor(n/3), ceil(n/3)]
 * (as even a split as possible, e.g. n=10 -> 4+3+3 in any order).
 */
export function hasBalancedInterviewDifficulties(
  easy: number,
  medium: number,
  hard: number,
  total: number
): boolean {
  if (total < 10) return false;
  if (easy + medium + hard !== total) return false;
  const low = Math.floor(total / 3);
  const high = Math.ceil(total / 3);
  return (
    easy >= low &&
    easy <= high &&
    medium >= low &&
    medium <= high &&
    hard >= low &&
    hard <= high
  );
}

export const INTERVIEW_QUESTIONS_BALANCE_REFINE_MESSAGE =
  'interview_questions must have at least 10 items and difficulties balanced: with n = length, each of easy, medium, hard must appear between floor(n/3) and ceil(n/3) times (e.g. n=10: exactly 4, 3, and 3 in some order)';

