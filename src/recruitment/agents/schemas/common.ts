/** Refine message for section-type coverage. Exported for use in consensus schema. */
export const ASSESSMENT_SECTIONS_REFINE_MESSAGE = `sections must contain exactly one section of each type: ${REQUIRED_ASSESSMENT_SECTION_TYPES.join(', ')}`;

/** Refine predicate: sections must contain exactly one section per assessment type. Exported for consensus schema. */
export function requireAllAssessmentSectionTypes(data: { sections: { type: string }[] }): boolean {
  const types = new Set(data.sections.map((s) => s.type));
  return (
    types.size === REQUIRED_ASSESSMENT_SECTION_TYPES.length &&
    REQUIRED_ASSESSMENT_SECTION_TYPES.every((t) => types.has(t))
  );
}

/** Base assessment shape without refine; use this when extending (e.g. consensus). */
export const AssessmentResultBaseObjectSchema = z.object({
  decision: DecisionEnumSchema,
  score: Score0To100Schema,
  signal_blocks: SignalBlocksSchema,
  demonstrated_strengths: StringArraySchema.optional(),
  declared_skills_to_validate: StringArraySchema.optional(),
  final_decision: DecisionEnumSchema.optional(),
  confidence: Score0To100Schema.optional(),
  sections: z.array(AssessmentSectionSchema),
});

export const AssessmentResultBaseSchema = AssessmentResultBaseObjectSchema.refine(
  requireAllAssessmentSectionTypes,
  { message: ASSESSMENT_SECTIONS_REFINE_MESSAGE }
);

/** Interview agents (stage_3): assessment shape plus structured sample questions with balanced difficulty. */
export const InterviewAssessmentSchema = AssessmentResultBaseObjectSchema.extend({
  interview_questions: z
    .array(InterviewQuestionSchema)
    .min(10)
    .describe(
      'At least 10 interview questions. Spread easy, medium, and hard as evenly as possible (for n items, each difficulty count must be floor(n/3) or ceil(n/3)).'
    ),
}).refine(
  (data) => {
    const qs = data.interview_questions;
    const { easy, medium, hard, total } = countInterviewQuestionDifficulties(qs);
    return hasBalancedInterviewDifficulties(easy, medium, hard, total);
  },
  { message: INTERVIEW_QUESTIONS_BALANCE_REFINE_MESSAGE, path: ['interview_questions'] }
);

export const AssessmentResultSchema = AssessmentResultBaseSchema;

export const RecruitmentDecisionOutputSchema = AssessmentResultSchema;

export function normalizeAssessmentScore(score: number): { score: number; corrected: boolean } {
  if (typeof score !== 'number' || Number.isNaN(score)) return { score, corrected: false };
  if (score >= 0 && score <= 10) {
    return { score: Math.round(score * 10), corrected: true };
  }
  return { score, corrected: false };
}

